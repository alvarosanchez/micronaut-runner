package io.micronaut.runner.gradle;

import io.micronaut.runner.build.BuildLogger;
import org.gradle.api.logging.Logger;

/** Bridges the packaging library's log calls to Gradle's logger. */
final class GradleBuildLogger implements BuildLogger {

    private final Logger logger;

    GradleBuildLogger(Logger logger) {
        this.logger = logger;
    }

    @Override
    public void info(String message) {
        logger.info(message);
    }

    @Override
    public void warn(String message) {
        logger.warn(message);
    }
}
