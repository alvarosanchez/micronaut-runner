package io.micronaut.runner.build;

import io.micronaut.runner.Index;

import java.io.InputStream;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.zip.CRC32;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;

/** Forked low-heap acceptance probe; kept out of the ordinary test JVM to avoid large fixture allocations. */
public final class BoundedMemoryPackagingProbe {

    private static final int LARGE_RESOURCE_SIZE = 48 * 1024 * 1024;
    private static final int SMALL_RESOURCE_COUNT = 64;
    private static final int SMALL_RESOURCE_SIZE = 512 * 1024;

    private BoundedMemoryPackagingProbe() {
    }

    /** Generates more expanded payload than the child heap, packages it, and streams it back under verify-all. */
    public static void main(String[] args) throws Exception {
        Path workspace = Files.createDirectories(Path.of(args[0]));
        Path applicationClass = Path.of(args[1]);
        Path application = workspace.resolve("application.jar");
        byte[] buffer = new byte[64 * 1024];
        fill(buffer);
        try (OutputStream file = Files.newOutputStream(application);
             ZipOutputStream zip = new ZipOutputStream(file)) {
            zip.putNextEntry(new ZipEntry("com/example/Application.class"));
            Files.copy(applicationClass, zip);
            zip.closeEntry();
            writeGenerated(zip, "large.bin", LARGE_RESOURCE_SIZE, buffer);
            for (int i = 0; i < SMALL_RESOURCE_COUNT; i++) {
                writeGenerated(zip, "many/entry-" + i + ".bin", SMALL_RESOURCE_SIZE, buffer);
            }
        }

        Path output = workspace.resolve("runner.jar");
        System.setProperty(RunnerJarBuilder.VERIFY_ALL_PROPERTY, "true");
        RunnerJarBuilder.build(RunnerJarSpec.builder()
                .mainClass("com.example.Application")
                .applicationOutput(List.of(application))
                .dependencies(List.of())
                .entryStub(false)
                .output(output)
                .build(), BuildLogger.noOp());

        try (RunnerJarReader reader = RunnerJarReader.open(output)) {
            Index index = reader.index();
            int record = index.find("large.bin");
            CRC32 crc = new CRC32();
            long count = 0;
            try (InputStream input = reader.source().stream(index.entryDataOffset(record),
                    index.entryCompressedSize(record), index.entryUncompressedSize(record),
                    index.entryMethod(record))) {
                int read;
                while ((read = input.read(buffer)) >= 0) {
                    crc.update(buffer, 0, read);
                    count += read;
                }
            }
            if (count != LARGE_RESOURCE_SIZE || crc.getValue() != index.entryCrc32(record)) {
                throw new AssertionError("large resource was not packaged byte-for-byte");
            }
        }
        System.out.println("packaged and verified " + (LARGE_RESOURCE_SIZE
                + (long) SMALL_RESOURCE_COUNT * SMALL_RESOURCE_SIZE) + " generated bytes");
    }

    private static void writeGenerated(ZipOutputStream zip, String name, int size, byte[] buffer)
            throws Exception {
        zip.putNextEntry(new ZipEntry(name));
        int remaining = size;
        while (remaining > 0) {
            int count = Math.min(remaining, buffer.length);
            zip.write(buffer, 0, count);
            remaining -= count;
        }
        zip.closeEntry();
    }

    private static void fill(byte[] buffer) {
        int state = 0x13579BDF;
        for (int i = 0; i < buffer.length; i++) {
            state ^= state << 13;
            state ^= state >>> 17;
            state ^= state << 5;
            buffer[i] = (byte) state;
        }
    }
}